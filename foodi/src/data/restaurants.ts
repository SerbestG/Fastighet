import type { Dish, OptionChoice, OptionGroup, Restaurant, WeekHours } from '../types';

const span = (open: string, close: string) => ({ open, close });
const daily = (open: string, close: string): WeekHours => Array.from({ length: 7 }, () => span(open, close));

/** Måndag–torsdag, fredag–lördag, söndag. */
function weekly(
  monThu: [string, string] | null,
  friSat: [string, string] | null,
  sun: [string, string] | null,
): WeekHours {
  const s = (v: [string, string] | null) => (v ? span(v[0], v[1]) : null);
  return [s(monThu), s(monThu), s(monThu), s(monThu), s(friSat), s(friSat), s(sun)];
}

const choice = (id: string, name: string, price = 0, photo?: string): OptionChoice => ({ id, name, price, photo });

function drinks(prefix: string, items: [string, string, number][]): OptionGroup {
  return {
    id: `${prefix}-dryck`,
    title: 'Lägg till dryck',
    kind: 'single',
    required: false,
    choices: items.map(([id, name, price]) => choice(id, name, price)),
  };
}

